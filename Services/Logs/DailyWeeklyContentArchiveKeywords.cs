        /// <summary>문구 중 하나라도 들어 있으면 true.</summary>
        public static bool ContainsAny(string text)
        {
            if (string.IsNullOrEmpty(text))
                return false;

            foreach (string keyword in All)
            {
                if (text.Contains(keyword, StringComparison.Ordinal))
                    return true;
            }

            return false;
        }
